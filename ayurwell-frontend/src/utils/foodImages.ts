export function getFoodImage(name: string): string {
  if (!name) return FOOD_IMAGES['default_food'];
  if (FOOD_IMAGES[name]) return FOOD_IMAGES[name];

  const lower = name.toLowerCase();

  // 1. Khichdi (always authentic Moong Dal Khichdi)
  if (lower.includes('khichdi')) {
    return '/images/moong_dal_khichdi.jpg';
  }

  // 2. Upma & Barley & Dalia
  if (lower.includes('barley') || lower.includes('upma') || lower.includes('jav') || lower.includes('dalia')) {
    return '/images/barley_vegetable_upma.jpg';
  }

  // 3. Raisins / Munakka & Soaked Almonds
  if (lower.includes('munakka') || lower.includes('raisin') || (lower.includes('almond') && lower.includes('soak'))) {
    return '/images/soaked_munakka_almonds.jpg';
  }

  // 4. CCF Elixir / Herbal Tea
  if (lower.includes('ccf') || lower.includes('elixir') || (lower.includes('cumin') && lower.includes('fennel'))) {
    return '/images/ccf_digestive_tea.jpg';
  }

  // 5. Lauki / Bottle Gourd & Soups
  if (lower.includes('lauki') || lower.includes('bottle gourd') || (lower.includes('soup') && lower.includes('moong'))) {
    return '/images/lauki_moong_soup.jpg';
  }

  // 6. Ragi / Finger Millet Porridge
  if (lower.includes('ragi') || lower.includes('finger millet') || lower.includes('millet porridge')) {
    return '/images/warm_ragi_porridge.jpg';
  }

  // 7. Makhana / Foxnuts
  if (lower.includes('makhana') || lower.includes('foxnut')) {
    return '/images/roasted_phool_makhana.jpg';
  }

  // 8. Cheela / Crepe
  if (lower.includes('cheela') || lower.includes('chilla')) {
    return '/images/moong_dal_cheela.jpg';
  }

  // 9. Jowar / Bhakri / Usal
  if (lower.includes('jowar') || lower.includes('bhakri') || lower.includes('usal') || lower.includes('sorghum') || lower.includes('takra')) {
    return '/images/jowar_bhakri_moong_usal.jpg';
  }

  // 10. Golden Turmeric Milk
  if (lower.includes('turmeric milk') || lower.includes('haldi') || lower.includes('golden milk') || (lower.includes('milk') && lower.includes('walnut'))) {
    return '/images/golden_turmeric_milk.jpg';
  }

  // 11. Amla / Gooseberry / Mint Detox
  if (lower.includes('amla') || lower.includes('gooseberry')) {
    return '/images/amla_mint_detox.jpg';
  }

  // 12. Coconut Rice Porridge / Kheer
  if (lower.includes('coconut rice') || lower.includes('kheer')) {
    return '/images/coconut_rice_porridge.jpg';
  }

  // 13. Idli & Sambar
  if (lower.includes('idli') || lower.includes('sambar')) {
    return 'https://images.unsplash.com/photo-1589301760014-d929f3979dbc?auto=format&fit=crop&w=600&q=80';
  }

  // 14. Tender Coconut Water
  if (lower.includes('coconut water') || lower.includes('sabja')) {
    return 'https://images.unsplash.com/photo-1525385133512-2f3bdd039054?auto=format&fit=crop&w=600&q=80';
  }

  // 15. Pomegranate / Dadima
  if (lower.includes('pomegranate') || lower.includes('dadima')) {
    return 'https://images.unsplash.com/photo-1615485290382-441e4d049cb5?auto=format&fit=crop&w=600&q=80';
  }

  // 16. General Herbal Teas
  if (lower.includes('tea') || lower.includes('brew') || lower.includes('tulsi')) {
    return '/images/ccf_digestive_tea.jpg';
  }

  // 17. General Moong / Lentils / Dal
  if (lower.includes('moong') || lower.includes('dal') || lower.includes('lentil')) {
    return '/images/moong_dal_khichdi.jpg';
  }

  // 18. Roti / Phulka
  if (lower.includes('roti') || lower.includes('phulka') || lower.includes('chapati')) {
    return '/images/lauki_moong_soup.jpg';
  }

  // 19. General Porridge
  if (lower.includes('porridge')) {
    return '/images/warm_ragi_porridge.jpg';
  }

  return FOOD_IMAGES['default_food'];
}
